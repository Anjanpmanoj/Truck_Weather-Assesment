import type { KeyboardEvent } from 'react'
import { formatDateTime, formatDuration, formatMiles } from '../lib/format'
import { RISK_META, RISK_ORDER } from '../lib/risk'
import type { RiskKey, Route } from '../types/route'

interface Props {
  routes: Route[]
  selectedId: string | null
  recommendedSafe: boolean
  onSelect: (id: string) => void
}

const PEAK_ORDER: RiskKey[] = ['severe', 'high', 'moderate', 'low']

// Worst level that covers at least a mile, so a tiny sliver does not define the route.
function peakRisk(route: Route): RiskKey {
  if (route.summary.has_no_travel) return 'no_travel'
  const miles = route.summary.miles_by_level
  const found = PEAK_ORDER.find((k) => miles[k] >= 1)
  if (found) return found
  return miles.unknown >= 1 ? 'unknown' : 'low'
}

function RiskBar({ route }: { route: Route }) {
  const miles = route.summary.miles_by_level
  const total = RISK_ORDER.reduce((sum, k) => sum + miles[k], 0) || 1
  const present = RISK_ORDER.filter((k) => miles[k] > 0)
  const description = present.map((k) => `${RISK_META[k].label} ${formatMiles(miles[k])}`).join(', ')
  return (
    <div>
      <div className="flex h-2.5 w-full overflow-hidden rounded-full bg-slate-800" role="img"
        aria-label={`Miles by risk level: ${description}`}>
        {present.map((k) => (
          <div key={k} title={`${RISK_META[k].label}: ${formatMiles(miles[k])}`}
            style={{ width: `${(miles[k] / total) * 100}%`, backgroundColor: RISK_META[k].color }} />
        ))}
      </div>
      <ul className="mt-2 flex flex-wrap gap-x-4 gap-y-1 text-xs text-slate-400">
        {present.filter((k) => miles[k] >= 0.5).map((k) => (
          <li key={k} className="flex items-center gap-1.5">
            <span className="h-2 w-2 rounded-full" style={{ backgroundColor: RISK_META[k].color }} />
            {RISK_META[k].label} {formatMiles(miles[k])}
          </li>
        ))}
      </ul>
    </div>
  )
}

function Stat({ label, value, sub }: { label: string; value: string; sub?: string }) {
  return (
    <div>
      <dt className="text-xs uppercase tracking-wide text-slate-500">{label}</dt>
      <dd className="mt-0.5 text-sm font-semibold text-slate-100">{value}</dd>
      {sub && <dd className="text-xs text-slate-500">{sub}</dd>}
    </div>
  )
}

export default function RouteCards({ routes, selectedId, recommendedSafe, onSelect }: Props) {
  const fastest = Math.min(...routes.map((r) => r.duration_s))

  return (
    <div role="radiogroup" aria-label="Route options" className="grid gap-4 sm:grid-cols-2 2xl:grid-cols-3">
      {routes.map((route) => {
        const selected = route.id === selectedId
        const peak = peakRisk(route)
        const peakColor = RISK_META[peak].color
        const extra = route.duration_s - fastest
        const unknownMiles = route.summary.miles_by_level.unknown

        const onKeyDown = (e: KeyboardEvent) => {
          if (e.key === 'Enter' || e.key === ' ') {
            e.preventDefault()
            onSelect(route.id)
          }
        }

        return (
          <div key={route.id} role="radio" aria-checked={selected} tabIndex={0}
            onClick={() => onSelect(route.id)} onKeyDown={onKeyDown}
            className={
              'cursor-pointer rounded-2xl border p-5 transition focus:outline-none focus-visible:ring-2 focus-visible:ring-sky-400 ' +
              (selected
                ? 'border-sky-500 bg-slate-900 ring-1 ring-sky-500/60'
                : 'border-slate-800 bg-slate-900/60 hover:border-slate-600')
            }>
            <div className="flex flex-wrap items-center gap-2">
              <h3 className="text-base font-semibold text-white">{route.label}</h3>
              {route.recommended && (
                <span className={
                  'rounded-full px-2 py-0.5 text-xs font-semibold ' +
                  (recommendedSafe ? 'bg-emerald-500/15 text-emerald-300' : 'bg-rose-500/15 text-rose-300')
                }>
                  {recommendedSafe ? '★ Recommended' : 'Best available, not safe'}
                </span>
              )}
              {route.source === 'waypoint-detour' && (
                <span className="rounded-full bg-slate-800 px-2 py-0.5 text-xs text-slate-300"
                  title="Generated by routing through an intermediate point, because the routing provider returned fewer than 3 routes.">
                  Via waypoint
                </span>
              )}
              <span className="ml-auto rounded-full border px-2 py-0.5 text-xs font-medium"
                style={{ color: peakColor, borderColor: peakColor, backgroundColor: `${peakColor}1a` }}>
                Peak: {RISK_META[peak].label}
              </span>
            </div>

            <dl className="mt-4 grid grid-cols-2 gap-x-4 gap-y-3">
              <Stat label="Distance" value={formatMiles(route.distance_mi)} />
              <Stat label="Duration" value={formatDuration(route.duration_s)}
                sub={extra >= 60 ? `+${formatDuration(extra)} vs fastest` : extra === 0 ? 'Fastest' : undefined} />
              <Stat label="Arrival (ETA)" value={formatDateTime(route.arrival_time)} />
              <Stat label="Average risk" value={`${route.summary.avg_risk.toFixed(1)} / 4`}
                sub={`${route.checkpoints.length} checkpoints`} />
            </dl>

            <div className="mt-4">
              <RiskBar route={route} />
              {unknownMiles >= 1 && (
                <p className="mt-2 text-xs text-amber-300">⚠ {formatMiles(unknownMiles)} without forecast data</p>
              )}
            </div>
          </div>
        )
      })}
    </div>
  )
}